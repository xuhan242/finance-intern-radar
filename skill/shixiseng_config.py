def std_company(name):
    """实习僧公司名 → 官网标准公司名；未命中返回 None（渠道独有）。"""
    if name in COMPANY_ALIAS:
        return COMPANY_ALIAS[name]
    if name in SAME_NAME:
        return name
    return None


def infer_org_type(name):
    import re
    if name in TYPE_OVERRIDE:
        return TYPE_OVERRIDE[name]
    for pat, t in TYPE_RULES:
        if re.search(pat, name):
            return t
    return "其他"
